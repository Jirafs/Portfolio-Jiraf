const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname,'../script.js'),'utf8');
const start = source.indexOf('if (achievementList) {');
const end = source.indexOf('menuButton?.addEventListener',start);
assert.ok(start > 0 && end > start);
const code = source.slice(start,end);
let reads=0, removed=0, added=[];
const storage={getItem(){reads++;return '[{"title":"Тест / 2026","description":"Описание"}]';},removeItem(){removed++;}};
const context={achievementList:null,localStorage:storage,addAchievement:(...a)=>added.push(a),console:{warn(){}}};
vm.runInNewContext(code,context);
assert.equal(reads,0,'Pages without a list must not load or erase achievements');
context.achievementList={};
vm.runInNewContext(code,context);
assert.deepEqual(added[0],['Тест','2026','Описание',false]);
storage.getItem=()=>'{broken';
vm.runInNewContext(code,context);
storage.getItem=()=>{throw new Error('denied');};
vm.runInNewContext(code,context);
assert.equal(removed,0);
console.log('PASS: achievements are loaded only on their page; malformed or blocked storage is preserved');
